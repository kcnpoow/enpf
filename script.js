function sendMsg() {
  var inp = document.getElementById("chatInp");
  var text = inp.value.trim();
  if (!text) return;
  inp.value = "";
  document.getElementById("chatSugg").style.display = "none";
  addMsg(text, true);
  showTyping(true);

  if (collectingLead) {
    setTimeout(function () {
      showTyping(false);
      handleLead(text);
    }, 700);
    return;
  }

  setTimeout(
    function () {
      showTyping(false);
      var reply = aiReply(text);
      addMsg(reply, false);
    },
    700 + Math.random() * 400,
  );
}

