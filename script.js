function adjAge() {
  var s = document.getElementById("ageSlider");
  s.min = vtype === "oppv" ? 40 : 45;
  if (parseInt(s.value) < parseInt(s.min)) s.value = s.min;
}
function fmt(n) {
  return Math.round(n).toLocaleString("ru-RU");
}
function setSl(id, val, min, max) {
  var el = document.getElementById(id);
  var p = Math.max(0, Math.min(100, ((val - min) / (max - min)) * 100));
  el.style.background =
    "linear-gradient(to right,var(--green) " + p + "%,#E5E7EB " + p + "%)";
}
function getTbl() {
  if (gender === "m" && vtype === "opv") return opvM;
  if (gender === "f" && vtype === "opv") return opvF;
  if (gender === "m" && vtype === "oppv") return oppvM;
  return oppvF;
}

function upd() {
  var age = parseInt(document.getElementById("ageSlider").value);
  var amt = parseInt(document.getElementById("amountSlider").value);
  document.getElementById("ageVal").textContent = age + " лет";
  document.getElementById("amountVal").textContent = fmt(amt) + " ₸";
  setSl(
    "ageSlider",
    age,
    parseInt(document.getElementById("ageSlider").min),
    73,
  );
  setSl("amountSlider", amt, 3000000, 80000000);
  var row = getTbl()[age];
  if (!row) {
    document.getElementById("monthlyOut").textContent = "—";
    document.getElementById("futureOut").textContent = "—";
    return;
  }
  var minNakop = row[1],
    minPay = row[2],
    delayed = row[0];
  var monthly = amt < minNakop ? 0 : Math.round(minPay * (amt / minNakop));
  var future = Math.round(monthly * Math.pow(1.08, 10));
  document.getElementById("monthlyOut").textContent =
    monthly > 0 ? fmt(monthly) + " ₸" : "Недостаточно накоплений";
  document.getElementById("futureOut").textContent =
    monthly > 0 ? fmt(future) + " ₸" : "—";
  var ti = document.getElementById("thInfo"),
    tt = document.getElementById("thText");
  if (amt < minNakop) {
    ti.className = "th-info warn";
    tt.textContent =
      "Нужно минимум " + fmt(minNakop) + " ₸ для возраста " + age + " лет";
  } else {
    ti.className = "th-info ok";
    tt.textContent =
      "✓ Порог пройден" +
      (delayed > 0 ? " · отложенный на " + delayed + " лет" : "") +
      " — можно оформить!";
  }
  // Update calc WA button
  var waText = encodeURIComponent(
    "Здравствуйте! Хочу рассчитать аннуитет.\nПол: " +
      (gender === "m" ? "Мужчина" : "Женщина") +
      "\nТип: " +
      (vtype === "opv" ? "ОПВ" : "ОППВ") +
      "\nВозраст: " +
      age +
      " лет\nНакопления: " +
      fmt(amt) +
      " ₸\nВыплата: " +
      (monthly > 0 ? fmt(monthly) + " ₸/мес" : "недостаточно"),
  );
  document.getElementById("calcWaBtn").href =
    "https://wa.me/77056669609?text=" + waText;
}

